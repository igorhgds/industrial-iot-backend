package henrique.igor.iiot.infrastructure.web.dtos.ruleGroup;

import henrique.igor.iiot.domain.entities.RuleGroup;
import henrique.igor.iiot.domain.entities.enums.LogicalOperator;
import henrique.igor.iiot.domain.entities.enums.Severity;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.OffsetDateTime;
import java.util.UUID;

@Schema(description = "Dynamic Rule Group representation returned by the API")
public record RuleGroupResponse(
        @Schema(description = "Unique identifier of the rule group", example = "cc0e8400-e29b-41d4-a716-446655440777")
        UUID ruleGroupId,

        @Schema(description = "Name of the rule group", example = "Sobrecarga Térmica e Vibração")
        String name,

        @Schema(description = "Description of the rule group", example = "Dispara alerta crítico quando temperatura > 85°C E vibração > 4.5 mm/s")
        String description,

        @Schema(description = "Identifier of the monitored equipment", example = "770e8400-e29b-41d4-a716-446655440222")
        UUID equipmentId,

        @Schema(description = "Code of the monitored equipment", example = "MTR-USI-001")
        String equipCode,

        @Schema(description = "Severity assigned to alerts generated by this rule group", example = "CRITICAL")
        Severity severity,

        @Schema(description = "Logical operator combining conditions", example = "AND")
        LogicalOperator operatorType,

        @Schema(description = "Whether the rule group is currently active", example = "true")
        Boolean isActive,

        @Schema(description = "Timestamp when the rule group was created", example = "2026-10-06T12:00:00Z")
        OffsetDateTime createdAt
) {
    public static RuleGroupResponse fromDomain(RuleGroup ruleGroup) {
        return new RuleGroupResponse(
                ruleGroup.getRuleGroupId(),
                ruleGroup.getName(),
                ruleGroup.getDescription(),
                ruleGroup.getEquipment() != null ? ruleGroup.getEquipment().getEquipmentId() : null,
                ruleGroup.getEquipment() != null ? ruleGroup.getEquipment().getEquipCode() : null,
                ruleGroup.getSeverity(),
                ruleGroup.getOperatorType(),
                ruleGroup.getActive(),
                ruleGroup.getCreatedAt()
        );
    }
}
